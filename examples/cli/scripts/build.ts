// `pnpm build`: compile the CLI (TUI included) into one executable for this
// machine, bin/locci-chat (git-ignored), with Bun's --compile.
//
// The TUI's Markdown parser, satteri, loads a native addon from a package
// named for the platform, which a compiled binary can't find on its own. So a
// generated entry embeds that addon and points satteri at it
// (NAPI_RS_NATIVE_LIBRARY_PATH, which its loader reads first), then loads the CLI.

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import * as path from 'node:path';

const root = path.resolve(import.meta.dir, '..');
const out = path.join(root, 'bin', 'locci-chat');

// satteri's own platform names: darwin-arm64, darwin-x64, linux-x64-gnu, ...
const report = process.report.getReport() as { header?: { glibcVersionRuntime?: string } };
const abi = { linux: report.header?.glibcVersionRuntime ? '-gnu' : '-musl', win32: '-msvc' }[process.platform as string] ?? '';
const target = `${process.platform}-${process.arch}${abi}`;
const fromSatteri = createRequire(createRequire(path.join(root, 'package.json')).resolve('satteri'));
const addon = fromSatteri.resolve(`@bruits/satteri-${target}`);

const entry = path.join(root, 'bin', '.entry.ts');
mkdirSync(path.dirname(entry), { recursive: true });
writeFileSync(
  entry,
  [
    '// Generated by scripts/build.ts.',
    `import addon from ${JSON.stringify(addon)} with { type: 'file' };`,
    'process.env.NAPI_RS_NATIVE_LIBRARY_PATH ??= addon;',
    `await import(${JSON.stringify(path.join(root, 'src', 'cli.ts'))});`,
    '',
  ].join('\n'),
);

try {
  const result = Bun.spawnSync(['bun', 'build', '--compile', entry, '--outfile', out], { cwd: root, stdio: ['inherit', 'inherit', 'inherit'] });
  if (result.exitCode !== 0) process.exit(result.exitCode ?? 1);
  console.log(`built ${path.relative(process.cwd(), out)} (${target})`);
} finally {
  rmSync(entry, { force: true });
}
