#!/usr/bin/env node
// Build examples/api/.env (and the cli/web .env files) for local development.
//
// Copies the tool keys and MCP settings from the original projects, as the
// examples mirror them, and mints a dedicated Locci API key through the local
// locci-auth. Never prints a secret. Existing .env files are left alone unless
// --force is given.
//
// Usage: node scripts/examples-env.mjs [--force]
//   CHAT_CLI_DIR   default ../locci-chat-cli
//   CHATBOT_DIR    default ../../web-apps/autonomous-chatbot
//   LOCCI_AUTH_DIR default ../locci-auth
//   LOCCI_AUTH_URL default http://localhost:8787

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const force = process.argv.includes('--force');
const chatCli = path.resolve(root, process.env.CHAT_CLI_DIR ?? '../locci-chat-cli');
const chatbot = path.resolve(root, process.env.CHATBOT_DIR ?? '../../web-apps/autonomous-chatbot');
const authUrl = process.env.LOCCI_AUTH_URL ?? 'http://localhost:8787';

/** KEY=value pairs from a dotenv file; inline "# comments" dropped. */
function readEnv(file) {
  if (!fs.existsSync(file)) {
    console.warn(`· ${file} not found; its values stay empty`);
    return {};
  }
  return Object.fromEntries(
    fs
      .readFileSync(file, 'utf8')
      .split('\n')
      .map((l) => l.match(/^([A-Z_][A-Z0-9_]*)=(.*)$/))
      .filter(Boolean)
      .map((m) => [m[1], m[2].replace(/\s+#.*$/, '').trim()]),
  );
}

function write(file, lines) {
  if (fs.existsSync(file) && !force) {
    console.log(`· ${path.relative(root, file)} exists; skipped (use --force to rebuild)`);
    return false;
  }
  fs.writeFileSync(file, lines.join('\n') + '\n', { mode: 0o600 });
  console.log(`✓ wrote ${path.relative(root, file)}`);
  return true;
}

/** A fresh API key named for the examples, via a short-lived user token. */
async function mintApiKey() {
  const token = execFileSync(path.join(root, 'scripts/locci-auth-token.sh'), { encoding: 'utf8' }).trim();
  if (!token) throw new Error('could not mint a locci-auth token (is `just auth` running?)');
  const res = await fetch(`${authUrl}/keys`, {
    method: 'POST',
    headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json' },
    body: JSON.stringify({ name: 'locci-ai-inference-examples' }),
  });
  if (!res.ok) throw new Error(`locci-auth /keys answered ${res.status}`);
  return (await res.json()).key;
}

const apiEnv = path.join(root, 'examples/api/.env');
if (!fs.existsSync(apiEnv) || force) {
  const web = readEnv(path.join(chatbot, '.env'));
  const cli = readEnv(path.join(chatCli, '.env'));
  const key = await mintApiKey();

  write(apiEnv, [
    '# Generated by scripts/examples-env.mjs; never commit. See .env.example.',
    '# Locci AI Gateway (via @locci/ai-sdk)',
    'LOCCI_AI_BASE_URL=http://localhost:8080/v1',
    `LOCCI_AUTH_URL=${authUrl}`,
    `LOCCI_API_KEY=${key}`,
    'MODEL=qwen3-1.7b',
    'PORT=3939',
    'CORS_ORIGIN=http://localhost:5173,http://localhost:4173',
    '',
    '# Web tools, from autonomous-chatbot/.env',
    `OPENWEATHERMAP_API_KEY=${web.OPENWEATHERMAP_API_KEY ?? ''}`,
    `FIRECRAWL_API_KEY=${web.FIRECRAWL_API_KEY ?? ''}`,
    '',
    '# MCP, from locci-chat-cli/.env',
    `MCP_ENABLED=${cli.MCP_ENABLED ?? '0'}`,
    'MCP_CONFIG=./mcp.json',
    `MCP_COMMAND=${cli.MCP_COMMAND ?? ''}`,
    `MCP_ARGS=${cli.MCP_ARGS ?? ''}`,
    '',
    '# Server-side threads (plumbing for later): THREAD_STORE=libsql',
    '# THREAD_STORE=libsql',
    '# THREADS_DB_URL=file:./data/threads.db',
  ]);
} else {
  console.log('· examples/api/.env exists; skipped (use --force to rebuild)');
}

const mcpJson = path.join(root, 'examples/api/mcp.json');
if (!fs.existsSync(mcpJson) && fs.existsSync(path.join(chatCli, 'mcp.json'))) {
  fs.copyFileSync(path.join(chatCli, 'mcp.json'), mcpJson);
  console.log('✓ copied mcp.json from locci-chat-cli');
}

for (const app of ['cli', 'web']) {
  const example = path.join(root, `examples/${app}/.env.example`);
  const target = path.join(root, `examples/${app}/.env`);
  if (!fs.existsSync(target) || force) {
    fs.copyFileSync(example, target);
    console.log(`✓ wrote examples/${app}/.env from .env.example`);
  }
}
